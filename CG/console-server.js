function executeAgentTool(baseCG, agentDir, isCustomAgentDir, callName, argsObj) {
  const args = argsObj && typeof argsObj === 'object' ? argsObj : {};
  const st = getAgentState(baseCG, agentDir, isCustomAgentDir);

  if (callName === 'switch_mode') {
    const targetMode = sanitizeModeName(args.mode);
    const modePath = path.join(agentDir, 'modes', targetMode + '.md');
    const memPath = path.join(agentDir, 'memory', targetMode + '.md');
    if (!fs.existsSync(modePath)) {
      if (args.createIfMissing !== false) {
        const instructions = args.modeInstructions
          ? String(args.modeInstructions)
          : `# Mode: ${targetMode}\n\nYou are in **${targetMode}** mode with Drew. Provide sharp, accurate tactical and recon assistance.\n`;
        fs.writeFileSync(modePath, instructions, 'utf8');
      } else {
        return { ok: false, error: `Mode "${targetMode}" does not exist.` };
      }
    } else if (args.modeInstructions) {
      recordBackupBeforeWrite(agentDir, modePath, `agent/modes/${targetMode}.md`);
      fs.writeFileSync(modePath, String(args.modeInstructions), 'utf8');
    }
    if (!fs.existsSync(memPath)) {
      fs.writeFileSync(memPath, `# ${targetMode} Memory & Notes\n\n- **Active Mode:** ${targetMode}\n`, 'utf8');
    }
    const cfgPath = path.join(agentDir, 'config.json');
    const newCfg = Object.assign({}, st.config, { activeMode: targetMode });
    fs.writeFileSync(cfgPath, JSON.stringify(newCfg, null, 2) + '\n', 'utf8');
    return {
      ok: true,
      summary: `switched mode → ${targetMode}`,
      activeMode: targetMode,
      memory: fs.readFileSync(memPath, 'utf8')
    };
  }

  if (callName === 'read_memory') {
    const m = sanitizeModeName(args.mode || st.activeMode);
    const memPath = path.join(agentDir, 'memory', m + '.md');
    const content = fs.existsSync(memPath) ? fs.readFileSync(memPath, 'utf8') : '';
    return { ok: true, summary: `read memory/${m}.md`, mode: m, content };
  }

  if (callName === 'write_memory') {
    const m = sanitizeModeName(args.mode || st.activeMode);
    const memPath = path.join(agentDir, 'memory', m + '.md');
    recordBackupBeforeWrite(agentDir, memPath, `agent/memory/${m}.md`);
    fs.writeFileSync(memPath, String(args.content || ''), 'utf8');
    return { ok: true, summary: `updated memory/${m}.md`, mode: m };
  }

  if (callName === 'update_mode_prompt') {
    const m = sanitizeModeName(args.mode || st.activeMode);
    const modePath = path.join(agentDir, 'modes', m + '.md');
    recordBackupBeforeWrite(agentDir, modePath, `agent/modes/${m}.md`);
    fs.writeFileSync(modePath, String(args.content || ''), 'utf8');
    return { ok: true, summary: `updated modes/${m}.md`, mode: m };
  }

  if (callName === 'update_system_prompt') {
    const sysPath = path.join(agentDir, 'system.md');
    recordBackupBeforeWrite(agentDir, sysPath, 'agent/system.md');
    fs.writeFileSync(sysPath, String(args.content || ''), 'utf8');
    return { ok: true, summary: 'updated agent/system.md' };
  }

  if (callName === 'list_cg_files') {
    const files = listCgFilesRecursive(baseCG, baseCG);
    return { ok: true, summary: 'listed CG/ files', files };
  }

  if (callName === 'read_cg_file') {
    const rel = String(args.relPath || '').replace(/^[/\\]+/, '');
    const resolved = path.resolve(baseCG, rel);
    if (!resolved.startsWith(baseCG) || path.basename(resolved) === '.env') {
      return { ok: false, error: 'Access denied' };
    }
    if (!fs.existsSync(resolved) || !fs.statSync(resolved).isFile()) {
      return { ok: false, error: 'File not found: ' + rel };
    }
    return { ok: true, summary: `read ${rel}`, relPath: rel, content: fs.readFileSync(resolved, 'utf8') };
  }

  if (callName === 'write_cg_file') {
    const rel = String(args.relPath || '').replace(/^[/\\]+/, '').replace(/\\/g, '/');
    const resolved = path.resolve(baseCG, rel);
    const forbidden = new Set(['.env', 'derived/dock.json', 'baked/FIELDS.json', 'baked/trade.log.json', 'dock.html']);
    if (!resolved.startsWith(baseCG) || forbidden.has(rel) || path.basename(resolved) === '.env') {
      return { ok: false, error: 'Write forbidden for path: ' + rel };
    }
    recordBackupBeforeWrite(agentDir, resolved, rel);
    fs.mkdirSync(path.dirname(resolved), { recursive: true });
    fs.writeFileSync(resolved, String(args.content || ''), 'utf8');
    return { ok: true, summary: `edited ${rel}`, relPath: rel };
  }

  if (callName === 'reload_ui') {
    return { ok: true, summary: 'reloading UI', reloadRequested: true };
  }

  return { ok: false, error: 'Unknown tool: ' + callName };
}

function callGeminiGenerateContent(apiKey, model, payload) {
  return new Promise((resolve, reject) => {
    const bodyStr = JSON.stringify(payload);
    const reqPath = `/v1beta/models/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(apiKey)}`;
    const req = https.request(
      {
        hostname: 'generativelanguage.googleapis.com',
        port: 443,
        path: reqPath,
        method: 'POST',
        headers: {
          'Content-Type': 'application/json; charset=utf-8',
          'Content-Length': Buffer.byteLength(bodyStr, 'utf8')
        },
        timeout: 45000
      },
      (res) => {
        let data = '';
        res.on('data', (chunk) => { data += chunk; });
        res.on('end', () => {
          try {
            const parsed = JSON.parse(data);
            if (res.statusCode >= 400) {
              const msg = (parsed && parsed.error && parsed.error.message) || `Gemini HTTP ${res.statusCode}`;
              reject(new Error(msg));
              return;
            }
            resolve(parsed);
          } catch (e) {
            reject(new Error('Invalid JSON from Gemini API'));
          }
        });
      }
    );
    req.on('error', reject);
    req.on('timeout', () => { req.destroy(new Error('Gemini request timed out')); });
    req.end(bodyStr);
  });
}

async function runGeminiAgentTurn(baseCG, agentDir, isCustomAgentDir, userMessage, userImages = []) {
  const apiKey = resolveApiKey(baseCG, agentDir, isCustomAgentDir);
  if (!apiKey) {
    const err = new Error('Missing GEMINI_API_KEY. Paste your key in the top bar.');
    err.statusCode = 400;
    throw err;
  }

  const initSt = getAgentState(baseCG, agentDir, isCustomAgentDir);
  const history = initSt.history.slice();
  const nowIso = new Date().toISOString();
  const userEntry = {
    role: 'user',
    text: userMessage || (userImages && userImages.length > 0 ? '(attached image)' : ''),
    ts: nowIso
  };
  if (Array.isArray(userImages) && userImages.length > 0) {
    userEntry.images = userImages;
  }
  history.push(userEntry);

  // Build Gemini contents from recent conversation history
  const contents = [];
  for (const h of history.slice(-24)) {
    if (h.role === 'user' || h.role === 'model') {
      const parts = [];
      if (h.role === 'user' && Array.isArray(h.images) && h.images.length > 0) {
        for (const img of h.images) {
          if (img && img.data) {
            parts.push({
              inlineData: {
                mimeType: img.mimeType || 'image/png',
                data: String(img.data).replace(/^data:image\/[a-zA-Z0-9+.-]+;base64,/i, '')
              }
            });
          }
        }
      }
      parts.push({ text: String(h.text || (parts.length > 0 ? '(attached image)' : '')) });
      contents.push({
        role: h.role,
        parts
      });
    }
  }

  const toolCalls = [];
  let reloadRequested = false;
  let finalReply = '';

  for (let turn = 0; turn < 4; turn++) {
    const curSt = getAgentState(baseCG, agentDir, isCustomAgentDir);
    const sysText = [
      curSt.systemPrompt.trim(),
      `--- ACTIVE MODE: ${curSt.activeMode.toUpperCase()} (Available modes: ${curSt.modes.join(', ')}) ---`,
      curSt.modePrompt.trim(),
      `--- ACTIVE MODE PERSISTENT MEMORY (agent/memory/${curSt.activeMode}.md) ---`,
      curSt.memory.trim()
    ].join('\n\n');

    const payload = {
      systemInstruction: { parts: [{ text: sysText }] },
      contents,
      tools: [{ functionDeclarations: AGENT_TOOL_DECLARATIONS }],
      generationConfig: {
        temperature: typeof curSt.config.temperature === 'number' ? curSt.config.temperature : 0.7
      }
    };

    const resp = await callGeminiGenerateContent(apiKey, normalizeGeminiModel(curSt.config.model), payload);
    const cand = resp && resp.candidates && resp.candidates[0];
    const parts = (cand && cand.content && Array.isArray(cand.content.parts)) ? cand.content.parts : [];
    if (parts.length === 0) {
      finalReply = finalReply || '(No response generated.)';
      break;
    }

    contents.push({ role: 'model', parts });

    const fnCalls = parts.filter(p => p && p.functionCall);
    const textChunks = parts.filter(p => p && typeof p.text === 'string').map(p => p.text);
    if (textChunks.length > 0) {
      finalReply = textChunks.join('\n').trim();
    }

    if (fnCalls.length === 0) {
      break;
    }

    const responseParts = [];
    for (const fcPart of fnCalls) {
      const fc = fcPart.functionCall;
      const result = executeAgentTool(baseCG, agentDir, isCustomAgentDir, fc.name, fc.args || {});
      if (result && result.reloadRequested) reloadRequested = true;
      toolCalls.push({
        name: fc.name,
        args: fc.args || {},
        summary: (result && result.summary) || fc.name,
        ok: Boolean(result && result.ok)
      });
      responseParts.push({
        functionResponse: {
          name: fc.name,
          response: result
        }
      });
    }
    contents.push({ role: 'user', parts: responseParts });
  }

  if (!finalReply && toolCalls.length > 0) {
    finalReply = 'Done — executed: ' + toolCalls.map(t => t.summary).join(', ') + '.';
  }

  history.push({
    role: 'model',
    text: finalReply,
    toolCalls,
    ts: new Date().toISOString()
  });
  writeHistory(agentDir, history);

  return {
    reply: finalReply,
    toolCalls,
    reloadRequested,
    state: getAgentState(baseCG, agentDir, isCustomAgentDir)
  };
}

function readJsonBody(req, res, maxBytes, cb) {
  let body = '';
  let tooLarge = false;
  req.on('data', chunk => {
    if (tooLarge) return;
    body += chunk;
    if (body.length > maxBytes) {
      tooLarge = true;
      send400(res, 'body too large');
      req.destroy();
    }
  });
  req.on('end', () => {
    if (tooLarge || req.destroyed) return;
    try {
      const j = body ? JSON.parse(body) : {};
      cb(j);
    } catch (e) {
      send400(res, 'invalid json');
    }
  });
}

