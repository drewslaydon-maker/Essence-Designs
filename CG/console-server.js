function sanitizeModeName(name) {
  const s = String(name || '').trim().toLowerCase().replace(/[^a-z0-9_-]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');
  return s || 'recon';
}

function parseEnvFile(filePath, keyName) {
  try {
    if (!fs.existsSync(filePath)) return null;
    const raw = fs.readFileSync(filePath, 'utf8');
    const lines = raw.split(/\r?\n/);
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq === -1) continue;
      const k = trimmed.slice(0, eq).trim();
      let v = trimmed.slice(eq + 1).trim();
      if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
        v = v.slice(1, -1);
      }
      if (k === keyName && v) return v;
    }
  } catch (e) {}
  return null;
}

function isLikelyValidGeminiKey(k) {
  if (!k || typeof k !== 'string') return false;
  const s = k.trim();
  if (!s) return false;
  // Reject Google Cloud project IDs accidentally pasted instead of API keys
  if (/^gen-lang-client-/i.test(s)) return false;
  return true;
}

function readOpenCodeGoogleKey() {
  try {
    const os = require('node:os');
    const home = os.homedir();
    const candidates = [
      path.join(home, '.local', 'share', 'opencode', 'auth.json'),
      path.join(home, 'AppData', 'Local', 'opencode', 'auth.json'),
      path.join(home, 'AppData', 'Roaming', 'opencode', 'auth.json')
    ];
    for (const c of candidates) {
      if (fs.existsSync(c)) {
        const j = JSON.parse(fs.readFileSync(c, 'utf8'));
        const k = j && j.google && typeof j.google.key === 'string' ? j.google.key.trim() : '';
        if (isLikelyValidGeminiKey(k)) return k;
      }
    }
  } catch (e) {}
  return '';
}

function resolveApiKey(baseCG, agentDir, isCustomAgentDir) {
  if (isCustomAgentDir) {
    const customKey = parseEnvFile(path.join(agentDir, '.env'), 'GEMINI_API_KEY') || '';
    return isLikelyValidGeminiKey(customKey) ? customKey : '';
  }
  const sources = [
    process.env.GEMINI_API_KEY ? process.env.GEMINI_API_KEY.trim() : '',
    parseEnvFile(path.join(agentDir, '.env'), 'GEMINI_API_KEY') || '',
    parseEnvFile(path.join(baseCG, '.env'), 'GEMINI_API_KEY') || '',
    parseEnvFile(path.join(path.dirname(baseCG), '.env'), 'GEMINI_API_KEY') || '',
    readOpenCodeGoogleKey()
  ];
  for (const cand of sources) {
    if (isLikelyValidGeminiKey(cand)) return cand;
  }
  return '';
}

function ensureAgentSeeded(agentDir, seedDir) {
  fs.mkdirSync(path.join(agentDir, 'modes'), { recursive: true });
  fs.mkdirSync(path.join(agentDir, 'memory'), { recursive: true });
  fs.mkdirSync(path.join(agentDir, '.backups'), { recursive: true });

  const cfgPath = path.join(agentDir, 'config.json');
  if (!fs.existsSync(cfgPath)) {
    const seedCfg = path.join(seedDir, 'config.json');
    if (fs.existsSync(seedCfg)) fs.copyFileSync(seedCfg, cfgPath);
    else fs.writeFileSync(cfgPath, JSON.stringify({ activeMode: 'rimworld', model: 'gemini-3.8-flash', temperature: 0.7 }, null, 2) + '\n', 'utf8');
  }

  const sysPath = path.join(agentDir, 'system.md');
  if (!fs.existsSync(sysPath)) {
    const seedSys = path.join(seedDir, 'system.md');
    if (fs.existsSync(seedSys)) fs.copyFileSync(seedSys, sysPath);
    else fs.writeFileSync(sysPath, '# Cephalon Ghost\nYou are Drew\'s personal gaming agent.\n', 'utf8');
  }

  for (const sub of ['modes', 'memory']) {
    const srcSub = path.join(seedDir, sub);
    const dstSub = path.join(agentDir, sub);
    if (fs.existsSync(srcSub)) {
      for (const f of fs.readdirSync(srcSub)) {
        if (f.endsWith('.md')) {
          const dstFile = path.join(dstSub, f);
          if (!fs.existsSync(dstFile)) {
            fs.copyFileSync(path.join(srcSub, f), dstFile);
          }
        }
      }
    }
  }
}

function backupFilePath(agentDir) {
  return path.join(agentDir, '.backups', 'last-backup.json');
}

function readBackupStack(agentDir) {
  const bp = backupFilePath(agentDir);
  if (!fs.existsSync(bp)) return [];
  try {
    const data = JSON.parse(fs.readFileSync(bp, 'utf8'));
    if (Array.isArray(data)) return data;
    if (data && typeof data === 'object' && data.targetPath) return [data];
  } catch (e) {}
  return [];
}

function recordBackupBeforeWrite(agentDir, targetPath, relLabel) {
  fs.mkdirSync(path.join(agentDir, '.backups'), { recursive: true });
  const existed = fs.existsSync(targetPath);
  const previousContent = existed ? fs.readFileSync(targetPath, 'utf8') : null;
  const stack = readBackupStack(agentDir);
  stack.push({
    timestamp: new Date().toISOString(),
    targetPath,
    relPath: relLabel || path.basename(targetPath),
    previousContent,
    existed
  });
  while (stack.length > 25) stack.shift();
  fs.writeFileSync(backupFilePath(agentDir), JSON.stringify(stack, null, 2) + '\n', 'utf8');
}

function revertLastBackup(agentDir) {
  const stack = readBackupStack(agentDir);
  if (stack.length === 0) return null;
  const last = stack.pop();
  const bp = backupFilePath(agentDir);
  if (stack.length === 0) {
    try { fs.unlinkSync(bp); } catch (e) {}
  } else {
    fs.writeFileSync(bp, JSON.stringify(stack, null, 2) + '\n', 'utf8');
  }
  if (last.existed && last.previousContent !== null && last.previousContent !== undefined) {
    fs.mkdirSync(path.dirname(last.targetPath), { recursive: true });
    fs.writeFileSync(last.targetPath, last.previousContent, 'utf8');
  } else if (!last.existed && fs.existsSync(last.targetPath)) {
    try { fs.unlinkSync(last.targetPath); } catch (e) {}
  }
  return last;
}

function normalizeGeminiModel(m) {
  const s = typeof m === 'string' ? m.trim() : '';
  if (!s || /^gemini-2\b/i.test(s) || /^gemini-2\./i.test(s)) return 'gemini-3.8-flash';
  return s;
}

function getAgentState(baseCG, agentDir, isCustomAgentDir) {
  ensureAgentSeeded(agentDir, path.join(baseCG, 'agent'));
  let config = { activeMode: 'rimworld', model: 'gemini-3.8-flash', temperature: 0.7 };
  try {
    config = Object.assign(config, JSON.parse(fs.readFileSync(path.join(agentDir, 'config.json'), 'utf8')));
  } catch (e) {}
  const activeMode = sanitizeModeName(config.activeMode);
  config.activeMode = activeMode;
  config.model = normalizeGeminiModel(config.model);

  const modesDir = path.join(agentDir, 'modes');
  const modes = fs.existsSync(modesDir)
    ? fs.readdirSync(modesDir).filter(f => f.endsWith('.md')).map(f => f.slice(0, -3)).sort()
    : ['recon', 'rimworld', 'warframe'];
  if (!modes.includes(activeMode)) modes.push(activeMode);

  const sysPath = path.join(agentDir, 'system.md');
  const modePath = path.join(agentDir, 'modes', activeMode + '.md');
  const memPath = path.join(agentDir, 'memory', activeMode + '.md');
  const histPath = path.join(agentDir, 'history.json');

  const systemPrompt = fs.existsSync(sysPath) ? fs.readFileSync(sysPath, 'utf8') : '';
  const modePrompt = fs.existsSync(modePath) ? fs.readFileSync(modePath, 'utf8') : `# Mode: ${activeMode}\n`;
  const memory = fs.existsSync(memPath) ? fs.readFileSync(memPath, 'utf8') : `# ${activeMode} Memory\n`;

  let history = [];
  if (fs.existsSync(histPath)) {
    try {
      const h = JSON.parse(fs.readFileSync(histPath, 'utf8'));
      if (Array.isArray(h)) history = h;
    } catch (e) {}
  }

  const hasKey = Boolean(resolveApiKey(baseCG, agentDir, isCustomAgentDir));
  const hasBackup = readBackupStack(agentDir).length > 0;

  return {
    config,
    hasKey,
    systemPrompt,
    modes,
    activeMode,
    modePrompt,
    memory,
    history,
    hasBackup
  };
}

function writeHistory(agentDir, history) {
  const capped = history.slice(-60);
  fs.writeFileSync(path.join(agentDir, 'history.json'), JSON.stringify(capped, null, 2) + '\n', 'utf8');
}

function listCgFilesRecursive(dir, baseDir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === '.backups' || entry.name === '.env' || entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    const rel = path.relative(baseDir, full).replace(/\\/g, '/');
    if (entry.isDirectory()) {
      listCgFilesRecursive(full, baseDir, out);
    } else {
      out.push(rel);
    }
  }
  return out;
}

