function getMime(p) {
  if (p.endsWith('.html')) return 'text/html; charset=utf-8';
  if (p.endsWith('.js')) return 'text/javascript; charset=utf-8';
  if (p.endsWith('.json')) return 'application/json; charset=utf-8';
  return 'text/plain; charset=utf-8';
}

function serveStatic(reqPath, res, baseDir) {
  const target = path.normalize(path.join(baseDir, reqPath));
  if (!target.startsWith(baseDir)) { send404(res); return; }
  fs.stat(target, (err, st) => {
    if (err || !st.isFile()) { send404(res); return; }
    const rs = fs.createReadStream(target);
    res.writeHead(200, { 'Content-Type': getMime(target) });
    rs.pipe(res);
  });
}

